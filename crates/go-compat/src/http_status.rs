#[cfg(test)]
mod tests {
    use super::status_text;

    /// The codes whose Go text differs from hyper's canonical reason, and an unknown code.
    #[test]
    fn status_text_is_go_s() {
        assert_eq!(status_text(404), "Not Found");
        assert_eq!(status_text(413), "Request Entity Too Large");
        assert_eq!(status_text(414), "Request URI Too Long");
        assert_eq!(status_text(416), "Requested Range Not Satisfiable");
        assert_eq!(status_text(418), "I'm a teapot");
        assert_eq!(status_text(599), "");
    }
}
